function rngFor(str) {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  let a = h >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function genValues(criteria, p, pen, rng) {
  const max = criteria.reduce((a, x) => a + x.max, 0);
  const want = Math.max(0, Math.min(max, Math.round(p * max) - pen));
  const v = {};
  let tot = 0;
  for (const x of criteria) {
    const val = Math.round(x.max * Math.min(1, Math.max(0, p + (rng() - 0.5) * 0.3)));
    v[x.id] = val;
    tot += val;
  }
  let guard = 3000;
  while (tot !== want && guard-- > 0) {
    const x = criteria[Math.floor(rng() * criteria.length)];
    if (tot < want && v[x.id] < x.max) { v[x.id]++; tot++; } else if (tot > want && v[x.id] > 0) { v[x.id]--; tot--; }
  }
  return v;
}

